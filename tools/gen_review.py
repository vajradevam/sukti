#!/usr/bin/env python3
"""Generate the scholar review packet from lexicon/lexicon.toml.

Produces docs/review/lexicon-review.txt and lexicon-review.csv. Corrections are
made in the TOML file only; this generator is re-run afterwards.
"""
import csv, io, os, tomllib

with open('lexicon/lexicon.toml','rb') as f: d = tomllib.load(f)
os.makedirs('docs/review', exist_ok=True)

# The lexicon is ITRANS. A few legacy Hindi strings still carry stray Devanagari
# combining marks; normalise them so generated artifacts stay pure ASCII.
def itrans_clean(s):
    s = str(s).replace('\u0901', 'M').replace('\u093c', '').replace('\u0949', '')
    return ''.join(c for c in s if not 0x0900 <= ord(c) <= 0x097f)

# CSV (machine-readable, one row per lexical entry)
with open('docs/review/lexicon-review.csv','w',newline='',encoding='utf-8') as f:
    w = csv.writer(f)
    w.writerow(['id','canonical_itrans','iast','kind','part_of_speech','root','gloss_en','gloss_sa',
                'aliases','status','rationale','alternatives'])
    for e in d['entry']:
        w.writerow([e['id'],itrans_clean(e['canonical']),itrans_clean(e['iast']),e['kind'],
                    itrans_clean(e['pos']),itrans_clean(e['root']),itrans_clean(e['gloss_en']),
                    itrans_clean(e['gloss_sa']),'|'.join(itrans_clean(a) for a in e['aliases']),
                    e['status'],itrans_clean(e['rationale']),
                    '|'.join(itrans_clean(a) for a in e['alternatives'])])

# Markdown (one sitting)
o = io.StringIO()
o.write('# Sūkti lexicon — scholar review packet\n\n')
o.write('**Please review in one sitting.** Every proposal below was written by a')
o.write(' non-scholar implementation engineer. Nothing is claimed to be')
o.write(' scholar-approved. Corrections should be made in `lexicon/lexicon.toml`;')
o.write(' the CSV and this file are generated by `tools/gen_review.py`.\n\n')
o.write('## What we ask you to check\n\n')
o.write('1. **Spelling and inflection** of each canonical ITRANS form (right stem,')
o.write(' right vibhakti, correct conjuncts, anusvāra/nasal conventions).\n')
o.write('2. **IAST** transliteration accuracy.\n')
o.write('3. Whether the chosen form is the clearest option for a programming')
o.write(' concept, given the alternatives listed.\n')
o.write('4. The **open grammatical questions** at the end.\n\n')
o.write('Status key: `validated-by-tool` = transliteration/normalisation round-trip')
o.write(' verified with Vidyut-lipi; `pending-scholar-review` = awaiting your')
o.write(' judgement. Tool validation does **not** imply grammatical approval.\n\n')

for kind in ['keyword','role','type']:
    entries = [e for e in d['entry'] if e['kind'] == kind]
    if not entries: continue
    o.write(f'## {kind.capitalize()} vocabulary ({len(entries)})\n\n')
    o.write('| id | ITRANS (canonical) | IAST | Part of speech / inflection | Root | Gloss (en) | Gloss (sa) | Aliases | Status | Rationale | Alternatives |\n')
    o.write('|---|---|---|---|---|---|---|---|---|---|---|\n')
    for e in entries:
        def c(x): return itrans_clean(x).replace('|','\\|').replace('\n',' ')
        o.write('| ' + ' | '.join([
            c(e['id']), c(e['canonical']), c(e['iast']), c(e['pos']), c(e['root'] or '—'),
            c(e['gloss_en']), c(e['gloss_sa']), c(', '.join(e['aliases']) or '—'),
            c(e['status']), c(e['rationale']), c(', '.join(e['alternatives']) or '—'),
        ]) + ' |\n')
    o.write('\n')

o.write('## Diagnostics (all user-facing messages)\n\n')
o.write('Every diagnostic appears in Sanskrit (sa), English (en) and Hindi (hi).')
o.write(' Placeholders use `{name}`.\n\n')
o.write('| code | sa | en | hi |\n|---|---|---|---|\n')
for m in d['message']:
    def c(x): return itrans_clean(x).replace('|','\\|')
    o.write(f"| {m['code']} | {c(m['sa'])} | {c(m['en'])} | {c(m['hi'])} |\n")
o.write('\n')

o.write('## Open grammatical questions for the scholar\n\n')
questions = [
 'Is `astu` (imperative 3sg of √as) idiomatic for a mutable binding, or is `bhavatu` preferable? Both are listed; we currently accept both.',
 'Is `nitya` acceptable adjectivally for an immutable binding, or should it be `nityam` / `achalam`?',
 'Are the imperative forms `virama`, `anuvarta`, `paTha`, `vada`, `Anaya`, `prakAshaya`, `utthApaya` correctly formed (dhātu, guṇa, endings)?',
 'Is `doShe` (locative sg.) the right catch-clause marker, or would `doSham` (accusative) be more idiomatic? Same question for `ante`.',
 'Are the seven kāraka labels (`kartA`, `karma`, `karaNa`, `sampradAna`, `apAdAna`, `adhikaraNa`, `sambandha`) correctly inflected as singular role names? We used nominative/accusative stems; should genitive forms be used instead?',
 'Is `sambandha` a defensible extension for a genitive-style parameter, or should we use `ShaShThI`?',
 'Are `pUrNA~nka`, `dashamalava`, `shabda`, `sUchI`, `kosha` acceptable modern technical terms for int/float/string/list/map? Is `koSha` merely a variant or a distinct form?',
 'Is `tantu` a respectful and clear term for a lightweight task, given its existing use as "thread/strand" in textual traditions?',
 'Are there any sandhi, conjunct or anusvāra conventions in the error messages that should be corrected for natural Sanskrit?',
 'Which of the listed alternatives should replace the current form, if any? Please mark entries `scholar-approved` in the TOML after correction.',
]
for i,q in enumerate(questions,1): o.write(f'{i}. {q}\n')
o.write('\n## Respect and scope note\n\n')
o.write('The language deliberately does not use mantras, deity names or sacred verses')
o.write(' in examples or tests. Classical sample texts are attributed and chosen')
o.write(' respectfully. The design makes no claim that Sanskrit is inherently')
o.write(' superior for computing; Pāṇinian ideas are used as *language semantics*')
o.write(' with documented simplifications, not as a mystical argument.\n')

open('docs/review/lexicon-review.txt','w',encoding='utf-8').write(o.getvalue())
print('wrote docs/review/lexicon-review.txt and lexicon-review.csv')
